import fs from 'node:fs';
import path from 'node:path';
const files=[];
for(const directory of ['src/lib','src/data','migrations']){
 for(const entry of fs.readdirSync(directory,{withFileTypes:true})){
  if(!entry.isFile()||entry.name.startsWith('lab_'))continue;
  const name=path.posix.join(directory,entry.name);
  if(/\.(js|sql)$/.test(name))files.push({name,data:fs.readFileSync(name,'utf8')});
 }
}
for(const name of ['public/figures.js','public/model.js','scripts/actions-runner.mjs','scripts/lib/d1-rest.mjs','scripts/lib/actions-runtime.mjs','scripts/lib/runner-diagnostics.mjs','.github/workflows/dcv-research.yml'])files.push({name,data:fs.readFileSync(name,'utf8')});
fs.writeFileSync('src/lib/lab_code_bundle.js','// Generated by scripts/prepare-lab-code.mjs. Contains no credentials.\nexport const REPLICATION_CODE='+JSON.stringify(files)+';\n');
console.log(`Bundled ${files.length} scientific source/schema files for submission packages.`);
